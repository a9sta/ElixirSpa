/** 둘레(km) 표기 — 100km 넘으면 정수, 10km 넘으면 한 자리, 그 밑은 두 자리 */
export function fk(v) {
  if (v >= 100) return `${Math.round(v)}km`;
  if (v >= 10) return `${v.toFixed(1)}km`;
  return `${v.toFixed(2)}km`;
}
export const fa = (a) => Number(a).toFixed(2);
export const fb = (b) => Number(b).toFixed(1);

