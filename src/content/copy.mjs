/** 굽이값을 말로 */
export function curveWord(a) {
  if (a < 1.04) return '자를 바꿔도 둘레가 거의 안 변해요';
  if (a < 1.065) return '자를 늘이면 둘레가 살짝만 줄어요';
  if (a < 1.095) return '자를 늘이면 둘레가 눈에 띄게 줄어요';
  if (a < 1.14) return '짧은 자일 때 잡히는 굴곡이 꽤 많아요';
  if (a < 1.2) return '짧은 자로 걸으면 둘레가 한참 늘어나요';
  return '짧은 자로 걸을 때 잔굴곡이 쏟아져 둘레가 가장 크게 불어나요';
}
/** 줄어듦(%)을 말로 */
export function shrinkWord(b) {
  if (b < 9) return '긴 자로 바꿔도 거의 줄지 않아요';
  if (b < 12.3) return '긴 자로 바꾸면 한 걸음 정도만 줄어요';
  if (b < 17.7) return '긴 자로 바꾸면 중간보다 조금 덜 줄어요';
  if (b < 25.5) return '긴 자로 바꾸면 중간보다 조금 더 줄어요';
  if (b < 34.7) return '긴 자로 바꾸면 둘레의 3분의 1 가까이 줄어요';
  return '긴 자로 바꾸면 둘레가 절반 가까이 사라져요';
}
/** 두 굽이값을 견준 말 */
export function cmpWord(x, y) {
  const d = x - y;
  if (Math.abs(d) < 0.015) return '거의 같은 값';
  return d > 0 ? '더 굽은 쪽' : '더 곧은 쪽';
}
